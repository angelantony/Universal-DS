import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { optimize } from 'svgo';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export async function optimizedIcons() {
  const directory = resolve(root, 'svg');
  const files = (await readdir(directory)).filter((file) => file.endsWith('.svg')).sort();
  /** @type {Record<string, string>} */
  const icons = {};
  for (const file of files) {
    const source = await readFile(resolve(directory, file), 'utf8');
    const result = optimize(source, {
      multipass: true,
      plugins: ['preset-default', { name: 'convertColors', params: { currentColor: true } }],
    });
    icons[file.replace(/\.svg$/, '')] = result.data;
  }
  return icons;
}

export function renderModule(icons) {
  const entries = Object.entries(icons)
    .map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
    .join('\n');
  return `import { iconRegistry } from './registry.js';\n\n/** Proprietary icons. Regenerated by scripts/optimize.mjs. */\nexport const builtInIcons = {\n${entries}\n} as const;\n\nexport function registerBuiltInIcons(): void {\n  iconRegistry.registerTrusted(builtInIcons);\n}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const icons = await optimizedIcons();
  const file = resolve(root, 'src/built-in.ts');
  const config = await prettier.resolveConfig(file);
  const source = await prettier.format(renderModule(icons), { ...config, filepath: file });
  await writeFile(file, source);
}
