import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { camelName } from '../../../tools/build/dtcg.mjs';
import {
  RESOLVED_JSON_FORMAT,
  TOKEN_FORMAT,
  registerResolvedJsonFormat,
  registerTokenFormats,
} from '../../../tools/build/token-css.mjs';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export async function buildTokens() {
  const pkg = JSON.parse(await readFile(resolve(packageRoot, 'package.json'), 'utf8'));
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: 'silent', errors: { brokenReferences: 'throw' } },
    source: [`${packageRoot}/src/tokens/**/*.json`],
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'uds',
        buildPath: `${packageRoot}/dist/`,
        files: [
          {
            destination: 'tokens.css',
            format: TOKEN_FORMAT,
            options: {
              layer: 'uds.tokens',
              layerOrder: 'uds.tokens, uds.theme, uds.brand',
              selector: ':root',
              version: pkg.version,
              reducedMotion: true,
              outputReferences: true,
            },
          },
        ],
      },
      resolved: {
        transformGroup: 'css',
        prefix: 'uds',
        buildPath: `${packageRoot}/dist/`,
        files: [{ destination: 'tokens.resolved.json', format: RESOLVED_JSON_FORMAT }],
      },
    },
  });
  registerTokenFormats(sd);
  registerResolvedJsonFormat(sd);
  await sd.buildAllPlatforms();
  const css = await readFile(resolve(packageRoot, 'dist/tokens.css'), 'utf8');
  await writeNamesModule(css, pkg.version);
  return {
    version: pkg.version,
    css,
    resolved: JSON.parse(await readFile(resolve(packageRoot, 'dist/tokens.resolved.json'), 'utf8')),
  };
}

/**
 * @param {string} css
 * @param {string} version
 */
async function writeNamesModule(css, version) {
  const names = [...css.matchAll(/--(uds-[a-z0-9-]+):/g)].map((match) => match[1]);
  const unique = [...new Set(names)].filter((name) => name !== 'uds-tokens-version').sort();
  const lines = unique.map((name) => {
    const key = camelName(name.replace(/^uds-/, '').split('-'));
    return `  ${key}: '--${name}',`;
  });
  const contents = `/** Generated by scripts/build.mjs. Do not edit. */\nexport const tokensVersion = '${version}' as const;\n\nexport const tokenNames = {\n${lines.join('\n')}\n} as const;\n\nexport type TokenName = (typeof tokenNames)[keyof typeof tokenNames];\n`;
  const target = resolve(packageRoot, 'src/generated/names.ts');
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  await buildTokens();
}
